// THE SKY TABLE — the physical atmosphere (`pwa/src/game/atmosphere-model.ts`,
// Hillaire's model) evaluated OFFLINE and baked into the small table every
// `SkyLook` and the LOW sky read (`pwa/src/game/sky-table.ts`, generated):
// by the sun's elevation (−20° to 90°, a degree apart through the twilights
// and sunrise, wider as it climbs) and the lens's altitude over the sea
// (the sea and 3 km), each row
//
//   * the SKY as a grid of radiance by the azimuth from the sun (0 toward
//     it, 180° away, packed toward the sun: u = √(az/π)) and the view's
//     elevation (packed toward the horizon: v = √(el/(π/2)));
//   * the SUN'S TRANSMITTANCE — the key's colour and strength;
//   * the SKY'S IRRADIANCE as L2 spherical harmonics in the sun's frame
//     (the sky above and the lit snow below), 27 numbers;
//
// over a ground of fresh snow. The radiances are packed as 16-bit codes of
// their base-2 logarithm (a step of a thousandth of a stop), the harmonics
// as numbers. Pure Node, a few seconds.
//
//   node scripts/sky-table.mjs            # the summary table only
//   node scripts/sky-table.mjs --write    # and rewrite pwa/src/game/sky-table.ts

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import process from "node:process";

import { parseArgs } from "@niclaslindstedt/oss-game-framework/tooling/cli";

import {
  createAtmosphere,
  EARTH,
  skyIrradianceSh,
  skyRadiance,
  SKY_GROUND_ALBEDO,
  sunThrough,
} from "../pwa/src/game/atmosphere-model.ts";
import {
  SKY_ALTITUDES,
  SKY_ELEVATIONS,
  SKY_VIEW_AZ,
  SKY_VIEW_EL,
  encodeRadiance,
  viewDirection,
} from "../pwa/src/game/sky-table-format.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const args = parseArgs(
  process.argv.slice(2),
  {
    write: { kind: "flag", help: "rewrite pwa/src/game/sky-table.ts" },
    steps: { kind: "number", default: 24, help: "the irradiance's samples a quarter turn" },
  },
  { usage: "node scripts/sky-table.mjs [--write]" },
);

const started = Date.now();
const atmo = createAtmosphere({ ...EARTH, albedo: SKY_GROUND_ALBEDO.snow });
const view = [];
const sun = [];
const sh = [];
const rows = [];
for (const altitude of SKY_ALTITUDES)
  for (const deg of SKY_ELEVATIONS) {
    const el = (deg * Math.PI) / 180;
    const s = { x: 0, y: Math.sin(el), z: Math.cos(el) };
    for (let j = 0; j < SKY_VIEW_EL; j++)
      for (let i = 0; i < SKY_VIEW_AZ; i++) {
        const L = skyRadiance(atmo, altitude, viewDirection(i, j), s);
        view.push(L[0], L[1], L[2]);
      }
    const T = sunThrough(atmo, altitude, el);
    sun.push(T[0], T[1], T[2]);
    const row = skyIrradianceSh(atmo, altitude, el, args.steps);
    sh.push(...row);
    if (altitude === SKY_ALTITUDES[0]) {
      const at = view.length - SKY_VIEW_AZ * SKY_VIEW_EL * 3;
      const zen = view.slice(
        at + (SKY_VIEW_EL - 1) * SKY_VIEW_AZ * 3,
        at + (SKY_VIEW_EL - 1) * SKY_VIEW_AZ * 3 + 3,
      );
      const hor = view.slice(at + 3 * (SKY_VIEW_AZ - 1), at + 3 * SKY_VIEW_AZ);
      rows.push({ deg, zen, hor, T: [...T], up: row.slice(0, 3) });
    }
  }

const lum = (c) => 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
const e = (x) => x.toExponential(2).padStart(9);
console.log("sun°   zenith L  b/r   anti-horizon L  b/r   sun T lum   r/b");
for (const r of rows)
  console.log(
    `${String(r.deg).padStart(4)}  ${e(lum(r.zen))}  ${(r.zen[2] / Math.max(1e-30, r.zen[0])).toFixed(2)}  ${e(lum(r.hor))}  ${(r.hor[2] / Math.max(1e-30, r.hor[0])).toFixed(2)}  ${e(lum(r.T))}  ${r.T[2] > 0 ? (r.T[0] / r.T[2]).toFixed(1) : "—"}`,
  );
console.log(
  `baked ${SKY_ALTITUDES.length * SKY_ELEVATIONS.length} rows in ${((Date.now() - started) / 1000).toFixed(1)} s`,
);

if (args.write) {
  const codes = new Uint16Array([...view, ...sun].map(encodeRadiance));
  const b64 = Buffer.from(codes.buffer).toString("base64");
  const lines = [];
  for (let k = 0; k < b64.length; k += 100) lines.push(`  "${b64.slice(k, k + 100)}"`);
  const shText = sh.map((x) => Number(x.toPrecision(4))).join(",");
  const out = `// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0
// GENERATED by \`make sky-table ARGS=--write\` (scripts/sky-table.mjs) off
// the physical atmosphere (atmosphere-model.ts) over fresh snow (albedo
// ${SKY_GROUND_ALBEDO.snow}) — never edited by hand. Its layout is
// sky-table-format.ts's; sky-atmosphere.ts reads it.

/** The sky's radiance grids, then the sun's transmittance, every row: the
 * base-2 logarithm's 16-bit codes (\`decodeRadiance\`), little-endian,
 * base64. */
export const SKY_TABLE_CODES =
${lines.join(" +\n")};

/** The sky's irradiance, L2 harmonics in the sun's frame, 27 a row. */
export const SKY_TABLE_SH = [${shText}];
`;
  writeFileSync(join(root, "pwa/src/game/sky-table.ts"), out);
  console.log(`wrote pwa/src/game/sky-table.ts (${(out.length / 1024).toFixed(1)} KB)`);
}
