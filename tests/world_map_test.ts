const VIEWS = [
  { w: 760, h: 480 },
  { w: 360, h: 380 },
  { w: 470, h: 200 },
];

const onScreen = (cam: Camera, view: { w: number; h: number }, lat: number, lon: number) => {
  const p = toScreen(cam, view, project({ lat, lon }));
  return p.x >= 0 && p.y >= 0 && p.x <= view.w && p.y <= view.h;
};

describe("the world map's outline (generated)", () => {
  const land = decodeLines(WORLD_LAND, WORLD_PRECISION);

  it("is small enough for a phone and decodes into lines on the globe", () => {
    const bytes = readFileSync("pwa/src/game/world-map-data.ts").length;
    expect(bytes).toBeLessThan(60 * 1024);
    for (const layer of [WORLD_LAND, WORLD_BORDERS, WORLD_LAKES]) {
      const lines = decodeLines(layer, WORLD_PRECISION);
      expect(lines.length).toBeGreaterThan(0);
      for (const pts of lines) {
        expect(pts.length % 2).toBe(0);
        for (let i = 0; i < pts.length; i += 2) {
          expect(Math.abs(pts[i])).toBeLessThanOrEqual(180.01);
          expect(Math.abs(pts[i + 1])).toBeLessThanOrEqual(90);
        }
      }
    }
    expect(land.reduce((n, l) => n + l.length / 2, 0)).toBeGreaterThan(2000);
    expect(pathOf(land, true)).toMatch(/^M[\d.]+ [\d.]+L/);
  });

  it("is generated, never edited by hand", () => {
    const text = readFileSync("pwa/src/game/world-map-data.ts", "utf8");
    expect(text).toMatch(/GENERATED by `make world-map ARGS=--write`/);
    expect(text).toMatch(/Natural Earth/);
  });

  it("has every real ski area on its land, or on its coast", () => {
    // Even-odd over every ring: a point is on land inside an odd count.
    const inside = (lon: number, lat: number): boolean => {
      let n = 0;
      for (const pts of land) {
        let hit = false;
        for (let i = 0, j = pts.length - 2; i < pts.length; j = i, i += 2) {
          const [xi, yi, xj, yj] = [pts[i], pts[i + 1], pts[j], pts[j + 1]];
          if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
        }
        if (hit) n++;
      }
      return n % 2 === 1;
    };
    // A town on a fjord the 1:50 m coast does not reach stands within a
    // few km of the shore drawn.
    const shoreKm = (lon: number, lat: number): number => {
      const k = Math.cos((lat * Math.PI) / 180);
      let best = Infinity;
      for (const pts of land) {
        for (let i = 0; i < pts.length; i += 2) {
          best = Math.min(best, 111.32 * Math.hypot((pts[i] - lon) * k, pts[i + 1] - lat));
        }
      }
      return best;
    };
    for (const id of REAL_FACE_IDS) {
      const at = realFacePlace(id)!;
      if (!inside(at.lon, at.lat)) expect(shoreKm(at.lon, at.lat), id).toBeLessThan(5);
    }
  });
});

describe("the world map's projection and camera", () => {
  it("projects and unprojects a point of the globe", () => {
    for (const p of [
      { lat: 63.4, lon: 13.1 },
      { lat: -33, lon: -70.5 },
      { lat: 0, lon: 0 },
    ]) {
      const back = unproject(project(p));
      expect(back.lat).toBeCloseTo(p.lat, 6);
      expect(back.lon).toBeCloseTo(p.lon, 6);
    }
    expect(project({ lat: 0, lon: -180 }).x).toBe(0);
    expect(project({ lat: 0, lon: 180 }).x).toBe(WORLD);
    // A unit at the equator is a thousandth of the earth; at 60° half that.
    expect(kmPerUnit(project({ lat: 0, lon: 0 }).y)).toBeCloseTo(40.075, 2);
    expect(kmPerUnit(project({ lat: 60, lon: 0 }).y)).toBeCloseTo(20.04, 1);
  });

  it("turns the screen and the plane into each other", () => {
    const view = VIEWS[0];
    const cam = { x: 530, y: 260, scale: 12 };
    const p = { x: 533, y: 255 };
    const q = toPlane(cam, view, toScreen(cam, view, p));
    expect(q.x).toBeCloseTo(p.x, 9);
    expect(q.y).toBeCloseTo(p.y, 9);
  });

  it("zooms about the point pressed and pans by the drag, inside its reach", () => {
    const view = VIEWS[0];
    const cam = worldTarget("fell-3", view);
    const at = { x: 200, y: 150 };
    const before = toPlane(cam, view, at);
    const zoomed = zoomAbout(cam, view, at, 1.5);
    const after = toPlane(zoomed, view, at);
    expect(after.x).toBeCloseTo(before.x, 6);
    expect(after.y).toBeCloseTo(before.y, 6);
    const panned = panBy(zoomed, view, 30, -12);
    expect((zoomed.x - panned.x) * zoomed.scale).toBeCloseTo(30, 6);
    // Never past the world, never closer than its closest.
    expect(zoomAbout(cam, view, at, 1e-6).scale).toBeCloseTo(minScale(view), 9);
    const close = zoomAbout(cam, view, at, 1e6);
    expect(close.scale).toBeCloseTo(maxScale(view, close.y), 6);
    expect(clampCamera({ x: -50, y: 0, scale: 0 }, view).x).toBe(0);
  });

  it("flies from the one camera to the other, bowing out over a long way", () => {
    const view = VIEWS[0];
    const a = worldTarget("alpine-1", view);
    const b = worldTarget("maritime-2", view);
    const start = flyAt(a, b, view, 0);
    const end = flyAt(a, b, view, 1);
    expect(start).toEqual({ x: a.x, y: a.y, scale: expect.closeTo(a.scale, 9) });
    expect(end.x).toBeCloseTo(b.x, 9);
    expect(end.scale).toBeCloseTo(b.scale, 9);
    // Half way to Japan the world is seen from far above both ends.
    expect(flyAt(a, b, view, 0.5).scale).toBeLessThan(Math.min(a.scale, b.scale) / 2);
    // Two neighbours are flown between without leaving the range.
    const c = worldTarget("fell-2", view);
    const d = worldTarget("fell-3", view);
    expect(flyAt(c, d, view, 0.5).scale).toBeGreaterThanOrEqual(Math.min(c.scale, d.scale) * 0.999);
  });

  it("measures the scale bar in round kilometres", () => {
    const cam = { x: 538, y: 240, scale: 40 };
    const bar = scaleBar(cam, 100);
    expect([1, 2, 5].some((m) => Number.isInteger(Math.log10(bar.km / m)))).toBe(true);
    expect(bar.px).toBeLessThanOrEqual(100);
    expect(bar.px).toBeGreaterThan(20);
  });
});

describe("the world map's markers", () => {
  it("are one a real ski area, at the middle of its parts, on a range's own land", () => {
    const marks = areaMarks();
    const areas = faceRanges().flatMap((r) => rangeAreas(r).map((a) => `${r}/${a}`));
    expect(marks.map((m) => m.key).sort()).toEqual([...areas].sort());
    expect(marks.flatMap((m) => m.faces).sort()).toEqual([...REAL_FACE_IDS].sort());
    for (const m of marks) {
      const parts = areaParts(m.range, m.area).map((p) => realFacePlace(p.id)!);
      const lat = parts.reduce((s, p) => s + p.lat, 0) / parts.length;
      expect(m.lat).toBeCloseTo(lat, 9);
    }
  });

  it("are pushed apart until two neighbours read as two, never far off their place", () => {
    const pts = [
      { x: 100, y: 100 },
      { x: 104, y: 101 },
      { x: 104, y: 101 },
      { x: 300, y: 40 },
    ];
    const out = declutter(pts, 18);
    for (let i = 0; i < out.length; i++) {
      for (let j = i + 1; j < out.length; j++) {
        expect(Math.hypot(out[i].x - out[j].x, out[i].y - out[j].y)).toBeGreaterThanOrEqual(17.9);
      }
    }
    expect(out[3]).toEqual(pts[3]);
    for (let i = 0; i < 3; i++) {
      expect(Math.hypot(out[i].x - pts[i].x, out[i].y - pts[i].y)).toBeLessThan(18);
    }
  });

  it("tell two ski areas of one range apart on its camera — and two of an area's mountains on its own", () => {
    for (const view of VIEWS) {
      // Every area of the picked one's range is on the screen, framed.
      for (const m of areaMarks()) {
        const cam = worldTarget(m.faces[0], view);
        for (const other of areaMarks().filter((o) => o.range === m.range)) {
          expect(onScreen(cam, view, other.lat, other.lon), `${m.key} → ${other.key}`).toBe(true);
        }
      }
      // An area's mountains, apart by more than a marker on the area step.
      for (const id of REAL_FACE_IDS) {
        const parts = partMarks(id);
        if (parts.length < 2) continue;
        const cam = areaTarget(id, view);
        const at = parts.map((p) => toScreen(cam, view, project(p)));
        for (const p of parts) expect(onScreen(cam, view, p.lat, p.lon)).toBe(true);
        expect(Math.hypot(at[0].x - at[1].x, at[0].y - at[1].y)).toBeGreaterThan(40);
      }
    }
    // The owner's own example: the two towns of one ski area, kept apart.
    const are = partMarks("fell-3").map((p) => p.part);
    expect(are).toContain("Duved");
    expect(are).toContain("Åre by");
  });

  it("gather a long chain into one counted cluster, and spread a short one", () => {
    // Twelve on a line, two px apart: one cluster at their middle.
    const line = Array.from({ length: 12 }, (_, i) => ({ x: 100 + 2 * i, y: 50 }));
    const lone = { x: 400, y: 300 };
    const out = groupMarks([...line, lone]);
    expect(out.length).toBe(2);
    const cluster = out.find((d) => d.members.length > 1)!;
    expect(cluster.members.length).toBe(12);
    expect(cluster.x).toBeCloseTo(111, 6);
    expect(out.find((d) => d.members.length === 1)).toMatchObject({ members: [12], ...lone });
    // Marked single, never gathered.
    const kept = groupMarks(
      line,
      undefined,
      undefined,
      line.map(() => true),
    );
    expect(kept.length).toBe(12);
    // Three: each its own, apart.
    const three = groupMarks(line.slice(0, 3));
    expect(three.map((d) => d.members.length)).toEqual([1, 1, 1]);
    // On the world's whole view the many real areas of Europe come together.
    const view = VIEWS[0];
    const cam = worldTarget(null, view);
    const world = groupMarks(areaMarks().map((m) => toScreen(cam, view, project(m))));
    expect(world.length).toBeLessThan(areaMarks().length);
    expect(world.flatMap((d) => d.members).sort((a, b) => a - b)).toEqual(
      areaMarks().map((_, i) => i),
    );
  });

  it("never leave the picked marker's label off", () => {
    const view = { w: 200, h: 100 };
    const marks = [
      { x: 100, y: 50 },
      { x: 112, y: 50 },
      { x: 88, y: 50 },
      { x: 100, y: 38 },
      { x: 100, y: 62 },
    ];
    const sizes = marks.map(() => ({ w: 50, h: 14 }));
    expect(placeLabels(marks, sizes, [0, 1, 2, 3, 4], view)[0]).not.toBeNull();
  });

  it("place each label clear of the others, the picked one first, or leave it off", () => {
    const view = { w: 300, h: 200 };
    const marks = [
      { x: 100, y: 100 },
      { x: 110, y: 100 },
      { x: 290, y: 190 },
    ];
    const sizes = marks.map(() => ({ w: 60, h: 16 }));
    const placed = placeLabels(marks, sizes, [1, 0, 2], view);
    expect(placed[1]?.side).toBe("right");
    const boxes = placed.filter((p) => p !== null);
    for (let i = 0; i < boxes.length; i++) {
      const a = boxes[i]!;
      expect(a.x).toBeGreaterThanOrEqual(0);
      expect(a.x + a.w).toBeLessThanOrEqual(view.w);
      for (const b of boxes.slice(i + 1)) {
        expect(a.x < b!.x + b!.w && b!.x < a.x + a.w && a.y < b!.y + b!.h && b!.y < a.y + a.h).toBe(
          false,
        );
      }
    }
    // A tap picks the marker within reach, the nearest of two.
    expect(nearestMark({ x: 103, y: 100 }, marks, 20)).toBe(0);
    expect(nearestMark({ x: 200, y: 20 }, marks, 20)).toBe(-1);
    // A tap on a marker's NAME picks it too, even far from its dot; a tap
    // on a dot beats a label lying over it.
    const named = [
      { at: { x: 100, y: 100 }, label: { x: 110, y: 90, w: 80, h: 16 } },
      { at: { x: 196, y: 98 }, label: null },
    ];
    expect(tappedMark({ x: 180, y: 96 }, named, 20)).toBe(0);
    expect(tappedMark({ x: 193, y: 98 }, named, 20)).toBe(1);
    expect(tappedMark({ x: 300, y: 300 }, named, 20)).toBe(-1);
  });

  it("stand GENERATED over the whole world", () => {
    const view = VIEWS[0];
    expect(markOf(null)).toBeNull();
    expect(worldTarget(null, view)).toEqual(worldCamera(view));
    expect(partMarks(null)).toEqual([]);
  });
});

describe("the WHERE steps", () => {
  it("walk the world, an area of several mountains, then the start card — and back", () => {
    const many = REAL_FACE_IDS.find((id) => hasAreaStep(id))!;
    const one = REAL_FACE_IDS.find((id) => !hasAreaStep(id))!;
    expect(stepAfter("play", null)).toBe("world");
    expect(stepAfter("world", many)).toBe("area");
    expect(stepAfter("area", many)).toBe("start");
    expect(stepAfter("world", one)).toBe("start");
    expect(stepAfter("world", null)).toBe("start");
    expect(stepBefore("start", many)).toBe("area");
    expect(stepBefore("start", one)).toBe("world");
    expect(stepBefore("start", null)).toBe("world");
    expect(stepBefore("area", many)).toBe("world");
    expect(stepBefore("world", many)).toBe("play");
    // Åre has two mountains, so it has an area step.
    expect(hasAreaStep("fell-1")).toBe(true);
    expect(markOf("fell-1")!.key).toBe(markOf("fell-3")!.key);
  });

  it("are reached by a link, which may stand the ride on a face", () => {
    for (const page of ["world", "area", "start"]) {
      const p = readParams(`?menu=${page}&face=fell-3`);
      expect(p.page).toBe(page);
      expect(freeRidePage(p.page)).toBe(true);
      expect(p.mode).toBe("free");
      expect(p.face).toBe("fell-3");
    }
    expect(freeRidePage("options")).toBe(false);
    const ride = freshRide();
    const on = rideOnFace(ride, "fell-3");
    expect(on.face).toBe("fell-3");
    expect(on.region).toBe("fell");
    expect(rideOnFace(ride, null)).toBe(ride);
    expect(rideOnFace(ride, "nowhere-9")).toBe(ride);
    expect(rideOnFace(on, "fell-3")).toBe(on);
  });
});
