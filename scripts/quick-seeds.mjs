// QUICK START'S SEEDS: the mountains the generator builds on its FIRST
// attempt, a list a country (`pwa/src/game/quick-seeds.ts`).
//
// A seed refused on its first attempt costs a whole ski area again for each
// attempt after it — measured, a random seed is built on its first attempt
// about one time in four, and a QUICK START dealt one at random waited two
// to five ski areas for its map. Dealt off this list, it waits for one.
//
//   npm run quick-seeds                      40 a country, printed
//   npm run quick-seeds -- --count 60 --write  …and written to the file
//
// Each country is searched on a thread of its own, through a stream of seeds
// of its own, so a run is the same list every time on the same generator.
// Re-run it when the generator's version moves: a seed that stops being a
// first-attempt seed is still a good mountain, only a slower one.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Worker, isMainThread, parentPort, workerData } from "node:worker_threads";
import process from "node:process";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

if (!isMainThread) {
  const { generateLevel, subSeed } = await import(join(root, "engine/mapgen/index.ts"));
  const { region, count, highest } = workerData;
  const salt = [...region].reduce((h, c) => (h * 31 + c.charCodeAt(0)) >>> 0, 7);
  const found = [];
  for (let i = 0; found.length < count; i++) {
    const seed = 1 + (subSeed(salt, i) % highest);
    const t0 = performance.now();
    try {
      // The first attempt alone: it throws where that attempt is refused.
      generateLevel(seed, { region, only: 0 });
      found.push(seed);
      parentPort.postMessage({ region, seed, ms: performance.now() - t0, tried: i + 1 });
    } catch {
      parentPort.postMessage({ region, seed: null, ms: performance.now() - t0, tried: i + 1 });
    }
  }
  parentPort.postMessage({ region, done: found });
} else {
  const { parseArgs } = await import("@niclaslindstedt/oss-game-framework/tooling/cli");
  const args = parseArgs(
    process.argv.slice(2),
    {
      count: { kind: "number", default: 40, help: "seeds a country" },
      regions: {
        kind: "list",
        default: ["alpine", "continental", "maritime", "fell"],
        help: "the countries, comma-separated",
      },
      write: { kind: "flag", help: "write pwa/src/game/quick-seeds.ts" },
    },
    "usage: npm run quick-seeds -- [--count n] [--regions a,b] [--write]",
  );
  const lists = {};
  await Promise.all(
    args.regions.map(
      (region) =>
        new Promise((done, fail) => {
          const w = new Worker(fileURLToPath(import.meta.url), {
            workerData: { region, count: args.count, highest: 999_999 },
          });
          w.on("message", (m) => {
            if (m.done) {
              lists[region] = m.done;
              done();
            } else
              console.log(
                `${region.padEnd(12)} #${String(m.tried).padStart(3)} ${String(m.seed ?? "refused").padStart(7)} ${(m.ms / 1000).toFixed(1)} s`,
              );
          });
          w.on("error", fail);
        }),
    ),
  );
  const body = args.regions.map((r) => `  ${r}: [\n${wrap(lists[r])}\n  ],`).join("\n");
  const file = `// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0
// GENERATED by \`npm run quick-seeds -- --write\` (scripts/quick-seeds.mjs) —
// never edited by hand.
//
// QUICK START'S SEEDS, a list a country: mountains the current generator
// builds on its FIRST attempt, so a quick start waits for one ski area
// rather than for the two to five a seed dealt at random costs.

import type { RegionId } from "@engine";

export const QUICK_START_SEEDS: Readonly<Record<RegionId, readonly number[]>> = {
${body}
};
`;
  if (args.write) {
    writeFileSync(join(root, "pwa/src/game/quick-seeds.ts"), file);
    console.log("wrote pwa/src/game/quick-seeds.ts");
  } else console.log(file);
}

function wrap(seeds) {
  const lines = [];
  for (let i = 0; i < seeds.length; i += 8) lines.push(`    ${seeds.slice(i, i + 8).join(", ")},`);
  return lines.join("\n");
}
